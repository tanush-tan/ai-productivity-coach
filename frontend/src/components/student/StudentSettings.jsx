import { useState, useEffect } from 'react';
import { getStoredToken } from '../../services/auth';
import { fetchStudentPairingStatus, redeemPairingCode } from '../../services/pairing';
import './StudentSettings.css';

/**
 * StudentSettings Component
 *
 * Provides workspace settings & device telemetry status for the student:
 *   - Profile details
 *   - Supervised device status & real parent pairing flow (code redemption)
 *   - Focus session preferences & privacy notices
 *   - Switch Role / Exit Student Workspace action
 */
function StudentSettings({ profile, dailyGoalMinutes, sessionsCount, onSwitchRole, currentUser, onGoToLogin, onPairingUpdated }) {
  const [pairingStatus, setPairingStatus] = useState(null);

  // Pairing code redemption form state
  const [code, setCode] = useState('');
  const [deviceName, setDeviceName] = useState('');
  const [deviceType, setDeviceType] = useState('laptop');
  const [isRedeeming, setIsRedeeming] = useState(false);
  const [redeemError, setRedeemError] = useState('');
  const [redeemSuccess, setRedeemSuccess] = useState('');
  const [refreshTrigger, setRefreshTrigger] = useState(0);
  const [showAddDevice, setShowAddDevice] = useState(false);

  useEffect(() => {
    let isMounted = true;

    async function load() {
      const token = getStoredToken();
      if (!token || !currentUser || currentUser.role !== 'student') {
        return;
      }

      try {
        const data = await fetchStudentPairingStatus(token);
        if (isMounted) {
          setPairingStatus(data);
          if (onPairingUpdated) {
            onPairingUpdated(data);
          }
        }
      } catch {
        // Ignored: demo fallback handled
      }
    }

    load();

    return () => {
      isMounted = false;
    };
  }, [currentUser, refreshTrigger, onPairingUpdated]);

  async function handleRedeemPairing(e) {
    e.preventDefault();
    const token = getStoredToken();
    if (!token) {
      setRedeemError('Please sign in with a student account to redeem a pairing code.');
      return;
    }

    if (!code.trim()) {
      setRedeemError('Please enter the pairing code generated by your parent.');
      return;
    }

    setIsRedeeming(true);
    setRedeemError('');
    setRedeemSuccess('');

    const cleanDeviceName = deviceName.trim() || `${currentUser?.displayName || 'Student'}'s Device`;

    try {
      const res = await redeemPairingCode(token, {
        code: code.trim(),
        deviceName: cleanDeviceName,
        deviceType,
      });

      setRedeemSuccess(
        `Successfully paired with ${res.parent?.displayName || 'Parent'}! Device registered as ${res.device?.name}.`
      );
      setCode('');
      setDeviceName('');
      setShowAddDevice(false);
      if (onPairingUpdated) {
        onPairingUpdated({
          isPaired: true,
          parent: res.parent,
          profile: pairingStatus?.profile,
          device: res.device,
        });
      }
      // Trigger refresh of pairing status
      setRefreshTrigger((prev) => prev + 1);
    } catch (err) {
      const msg = err.message || 'Failed to redeem pairing code.';
      if (msg.toLowerCase().includes('different parent')) {
        setRedeemError(
          `This pairing code belongs to a different parent account. Your student account is already linked to ${parentName || 'your parent'} and cannot be transferred.`
        );
      } else if (msg.toLowerCase().includes('too many failed') || msg.toLowerCase().includes('wait 10 minutes')) {
        setRedeemError(
          'Too many failed pairing attempts. Please wait 10 minutes before trying again.'
        );
      } else {
        setRedeemError(msg);
      }
    } finally {
      setIsRedeeming(false);
    }
  }

  const isPaired = pairingStatus?.isPaired;
  const parentName = pairingStatus?.parent?.displayName;
  const parentEmail = pairingStatus?.parent?.email;
  const pairedDevice = pairingStatus?.device;

  return (
    <div className="student-settings-view">
      {/* 1. Student Profile Card */}
      <div className="settings-card">
        <div className="settings-card-header">
          <div className="settings-avatar-wrap">
            <div className="settings-avatar-large" aria-hidden="true">
              {currentUser?.displayName
                ? currentUser.displayName
                    .split(' ')
                    .filter(Boolean)
                    .map((n) => n[0])
                    .join('')
                    .toUpperCase()
                    .slice(0, 2)
                : profile.initials}
            </div>
            <div>
              <h3 className="settings-profile-name">
                {currentUser?.displayName || profile.name}
              </h3>
              <span className="settings-profile-role">
                {currentUser ? 'Authenticated Student' : 'Student / Learner (Demo Mode)'}
              </span>
            </div>
          </div>
          <span className="profile-active-tag">
            {currentUser ? 'Live Account' : 'Demo Mode'}
          </span>
        </div>

        <div className="settings-info-grid">
          <div className="settings-info-item">
            <span className="item-label">Account Email</span>
            <span className="item-value">{currentUser?.email || 'guest@demo.local'}</span>
          </div>
          <div className="settings-info-item">
            <span className="item-label">Grade / Year</span>
            <span className="item-value">{pairingStatus?.profile?.grade || profile.grade}</span>
          </div>
          <div className="settings-info-item">
            <span className="item-label">Parent Supervision</span>
            <span className="item-value" style={{ color: isPaired ? '#10b981' : 'var(--text-secondary)' }}>
              {isPaired ? `Paired (${parentName})` : 'Unpaired'}
            </span>
          </div>
          <div className="settings-info-item">
            <span className="item-label">Active Device</span>
            <span className="item-value">{pairedDevice?.name || profile.device}</span>
          </div>
        </div>
      </div>

      {/* 2. Supervised Device & Parent Pairing */}
      <div className="settings-card">
        <div className="settings-section-head">
          <div>
            <h3 className="settings-title">Device &amp; Parental Supervision</h3>
            <p className="settings-desc">Link this computer with your parent’s supervision dashboard</p>
          </div>
          <span
            className="settings-demo-pill"
            style={{
              backgroundColor: isPaired ? 'rgba(16, 185, 129, 0.15)' : 'rgba(234, 179, 8, 0.15)',
              color: isPaired ? '#10b981' : '#eab308',
              border: `1px solid ${isPaired ? 'rgba(16, 185, 129, 0.3)' : 'rgba(234, 179, 8, 0.3)'}`,
            }}
          >
            {isPaired ? 'Paired & Supervised' : (currentUser ? 'Awaiting Pairing' : 'Demo Host')}
          </span>
        </div>

        {/* If student is not logged in with a real account */}
        {!currentUser && (
          <div style={{ padding: '16px', background: 'rgba(255, 255, 255, 0.03)', borderRadius: '8px', border: '1px dashed var(--border-color, #334155)' }}>
            <p style={{ margin: '0 0 12px 0', fontSize: '13px', color: 'var(--text-secondary)' }}>
              You are currently viewing the student portal in guest mode. Sign in with your student account to link this device with your parent’s dashboard using a pairing code.
            </p>
            {onGoToLogin && (
              <button
                type="button"
                onClick={onGoToLogin}
                style={{
                  background: 'var(--primary-color, #4f46e5)',
                  color: '#ffffff',
                  border: 'none',
                  borderRadius: '6px',
                  padding: '8px 16px',
                  fontSize: '13px',
                  fontWeight: '600',
                  cursor: 'pointer',
                }}
              >
                Sign In or Register as Student &rarr;
              </button>
            )}
          </div>
        )}

        {/* If student is authenticated and already paired */}
        {currentUser && isPaired && (
          <div className="device-status-box">
            <div className="device-row">
              <div className="device-icon" aria-hidden="true">💻</div>
              <div className="device-details">
                <span className="device-name">{pairedDevice?.name || 'Student Device'}</span>
                <span className="device-sub">
                  Code: {pairedDevice?.deviceCode || 'DEV-PAIRED'} &bull; {pairedDevice?.deviceType || 'laptop'} &bull; Offline (Awaiting Session)
                </span>
              </div>
              <div className="device-state-indicator">
                <span
                  className="device-dot"
                  style={{ backgroundColor: pairedDevice?.status === 'online' ? '#10b981' : '#94a3b8' }}
                  aria-hidden="true"
                />
                <span style={{ color: pairedDevice?.status === 'online' ? '#10b981' : '#94a3b8' }}>
                  {pairedDevice?.status === 'online' ? 'Online' : 'Offline'}
                </span>
              </div>
            </div>

            <div className="supervision-features-list">
              <div className="supervision-item">
                <span className="sup-icon" aria-hidden="true">🛡️</span>
                <div>
                  <strong>Supervised by {parentName} ({parentEmail})</strong>
                  <p>Device linked with parent supervision. Active telemetry and real-time monitoring will begin in Phase 4 when study sessions are active.</p>
                </div>
              </div>
            </div>

            {/* Toggle button to add an additional device */}
            <div style={{ borderTop: '1px solid var(--border-light, #334155)', paddingTop: '12px', display: 'flex', justifyContent: 'flex-end' }}>
              <button
                type="button"
                onClick={() => {
                  setShowAddDevice((prev) => !prev);
                  setRedeemError('');
                  setRedeemSuccess('');
                }}
                style={{
                  background: showAddDevice ? 'rgba(239, 68, 68, 0.1)' : 'rgba(79, 70, 229, 0.1)',
                  border: `1px solid ${showAddDevice ? 'rgba(239, 68, 68, 0.3)' : 'rgba(79, 70, 229, 0.3)'}`,
                  color: showAddDevice ? '#fca5a5' : '#a5b4fc',
                  padding: '7px 14px',
                  borderRadius: '6px',
                  fontSize: '13px',
                  fontWeight: '600',
                  cursor: 'pointer',
                }}
              >
                {showAddDevice ? '✕ Cancel Adding Device' : '+ Connect an Additional Device'}
              </button>
            </div>
          </div>
        )}

        {/* Pairing Code Form: Shown when not paired OR when adding an additional device */}
        {currentUser && (!isPaired || showAddDevice) && (
          <div style={{ marginTop: isPaired ? '12px' : '0' }}>
            {pairingStatus === null ? (
              <p style={{ color: 'var(--text-secondary)', fontSize: '13px' }}>Checking supervision status…</p>
            ) : (
              <form onSubmit={handleRedeemPairing} style={{ display: 'flex', flexDirection: 'column', gap: '14px', background: isPaired ? 'rgba(15, 23, 42, 0.4)' : 'transparent', padding: isPaired ? '16px' : '0', borderRadius: isPaired ? '10px' : '0', border: isPaired ? '1px solid var(--border-color, #334155)' : 'none' }}>
                <div>
                  <h4 style={{ margin: '0 0 4px 0', fontSize: '14px', fontWeight: '700', color: 'var(--text-primary)' }}>
                    {isPaired ? 'Connect an Additional Device' : 'Link Student Device'}
                  </h4>
                  <p style={{ fontSize: '13px', color: 'var(--text-secondary)', margin: '0', lineHeight: '1.4' }}>
                    {isPaired
                      ? `To connect a second computer, laptop, or tablet under your existing parent supervision, ask ${parentName || 'your parent'} to generate a fresh pairing code on their Connected Devices dashboard. Adding a device registers this hardware with your parent's supervision; it does not transfer your account to another parent.`
                      : 'Ask your parent to open the Connected Devices page on their dashboard and click “Connect Device” to get a one-time 12-character pairing code.'}
                  </p>
                </div>

                {redeemError && (
                  <div style={{ background: 'rgba(239, 68, 68, 0.1)', border: '1px solid rgba(239, 68, 68, 0.3)', padding: '10px 14px', borderRadius: '6px', color: '#fca5a5', fontSize: '13px' }}>
                    {redeemError}
                  </div>
                )}

                {redeemSuccess && (
                  <div style={{ background: 'rgba(16, 185, 129, 0.1)', border: '1px solid rgba(16, 185, 129, 0.3)', padding: '10px 14px', borderRadius: '6px', color: '#6ee7b7', fontSize: '13px' }}>
                    {redeemSuccess}
                  </div>
                )}

                <div style={{ display: 'flex', flexDirection: 'column', gap: '6px' }}>
                  <label htmlFor="student-pair-code" style={{ fontSize: '13px', fontWeight: '600', color: 'var(--text-primary)' }}>
                    One-Time Pairing Code
                  </label>
                  <input
                    id="student-pair-code"
                    type="text"
                    placeholder="e.g. K7P9-M2W4-X8R3"
                    value={code}
                    onChange={(e) => setCode(e.target.value)}
                    style={{
                      background: 'var(--bg-primary, #0f172a)',
                      border: '1px solid var(--border-color, #334155)',
                      borderRadius: '8px',
                      padding: '10px 14px',
                      color: 'var(--text-primary)',
                      fontSize: '15px',
                      fontFamily: 'monospace',
                      letterSpacing: '1px',
                    }}
                  />
                </div>

                <div style={{ display: 'grid', gridTemplateColumns: '2fr 1fr', gap: '12px' }}>
                  <div style={{ display: 'flex', flexDirection: 'column', gap: '6px' }}>
                    <label htmlFor="student-pair-device" style={{ fontSize: '13px', fontWeight: '600', color: 'var(--text-primary)' }}>
                      Device Name
                    </label>
                    <input
                      id="student-pair-device"
                      type="text"
                      placeholder={currentUser?.displayName ? `${currentUser.displayName}’s Device` : 'e.g. Study Laptop, Desktop'}
                      value={deviceName}
                      onChange={(e) => setDeviceName(e.target.value)}
                      style={{
                        background: 'var(--bg-primary, #0f172a)',
                        border: '1px solid var(--border-color, #334155)',
                        borderRadius: '8px',
                        padding: '10px 14px',
                        color: 'var(--text-primary)',
                        fontSize: '14px',
                      }}
                    />
                  </div>

                  <div style={{ display: 'flex', flexDirection: 'column', gap: '6px' }}>
                    <label htmlFor="student-pair-type" style={{ fontSize: '13px', fontWeight: '600', color: 'var(--text-primary)' }}>
                      Device Type
                    </label>
                    <select
                      id="student-pair-type"
                      value={deviceType}
                      onChange={(e) => setDeviceType(e.target.value)}
                      style={{
                        background: 'var(--bg-primary, #0f172a)',
                        border: '1px solid var(--border-color, #334155)',
                        borderRadius: '8px',
                        padding: '10px 14px',
                        color: 'var(--text-primary)',
                        fontSize: '14px',
                      }}
                    >
                      <option value="laptop">Laptop</option>
                      <option value="desktop">Desktop</option>
                      <option value="tablet">Tablet</option>
                      <option value="phone">Phone</option>
                      <option value="other">Other</option>
                    </select>
                  </div>
                </div>

                <button
                  type="submit"
                  disabled={isRedeeming}
                  style={{
                    alignSelf: 'flex-start',
                    background: 'var(--primary-color, #4f46e5)',
                    color: '#ffffff',
                    border: 'none',
                    borderRadius: '8px',
                    padding: '10px 20px',
                    fontSize: '14px',
                    fontWeight: '600',
                    cursor: isRedeeming ? 'not-allowed' : 'pointer',
                    marginTop: '6px',
                  }}
                >
                  {isRedeeming ? 'Validating & Linking…' : (isPaired ? 'Link Additional Device' : 'Pair with Parent Dashboard')}
                </button>
              </form>
            )}
          </div>
        )}
      </div>

      {/* 3. Session & Privacy Preferences */}
      <div className="settings-card">
        <div className="settings-section-head">
          <div>
            <h3 className="settings-title">Workspace Configuration</h3>
            <p className="settings-desc">Summary of current student defaults</p>
          </div>
        </div>

        <div className="settings-table-list">
          <div className="settings-table-row">
            <span className="row-key">Daily Target</span>
            <span className="row-val">{dailyGoalMinutes} minutes ({Math.floor(dailyGoalMinutes / 60)}h {dailyGoalMinutes % 60}m)</span>
          </div>
          <div className="settings-table-row">
            <span className="row-key">Total Sessions Logged</span>
            <span className="row-val">{sessionsCount} focus sessions</span>
          </div>
          <div className="settings-table-row">
            <span className="row-key">Distraction Detection</span>
            <span className="row-val">Manual Mode (Prototype)</span>
          </div>
        </div>
      </div>

      {/* 4. Switch Role / Exit */}
      <div className="settings-card settings-exit-card">
        <div>
          <h3 className="exit-title">Switch Role or Sign Out</h3>
          <p className="exit-desc">
            Return to the role-selection welcome screen to switch accounts.
          </p>
        </div>

        <button
          type="button"
          className="exit-role-btn"
          onClick={onSwitchRole}
        >
          <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
            <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4" />
            <polyline points="16 17 21 12 16 7" />
            <line x1="21" y1="12" x2="9" y2="12" />
          </svg>
          <span>Exit to Role Selection</span>
        </button>
      </div>
    </div>
  );
}

export default StudentSettings;
